const brevo = require('@getbrevo/brevo');
const path = require('path');
const fs = require('fs');

// Initialize Brevo API client
const apiInstance = new brevo.TransactionalEmailsApi();
apiInstance.setApiKey(
  brevo.TransactionalEmailsApiApiKeys.apiKey,
  process.env.BREVO_API_KEY
);

// Helper: Generate email address from company name
function generateEmailAddress(companyName) {
  if (!companyName) return `admin_unknown@${process.env.EMAIL_FROM_DOMAIN}`;

  // Sanitize company name: lowercase, remove special chars, max 50 chars
  const sanitized = companyName
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '') // Remove spaces
    .replace(/\./g, '') // Remove dots
    .replace(/,/g, '') // Remove commas
    .replace(/[^a-z0-9]/g, '') // Remove all non-alphanumeric
    .substring(0, 50);

  return `admin_${sanitized}@${process.env.EMAIL_FROM_DOMAIN}`;
}

